// summary draws page 1: the header, scope, and kills and losses
func (d *pageDoc) summary(in Input) {
	t := in.Target
	textX := pageMargin
	top := d.GetY()
	logoSize := 0.0
	if len(t.Logo) > 0 {
		logoSize = 26
		if d.logo(t.Logo, pageMargin, top, logoSize) {
			textX = pageMargin + logoSize + 5
		} else {
			logoSize = 0
		}
	}

	d.stamp(pageWidth-pageMargin-stampW, top+2, stampW)
	d.SetXY(textX, top)
	d.text(colText)
	// a long name shrinks to fit beside its ticker and the stamp, down to 14 pt, then is cut short
	width := pageWidth - pageMargin - stampW - 4 - textX
	ticker := ""
	if t.Ticker != "" {
		d.sans("", 14)
		ticker = "[" + t.Ticker + "]"
		width -= d.GetStringWidth(ticker) + 2
	}
	size := 22.0
	for d.sans("B", size); size > 14 && d.GetStringWidth(t.Name)+2 > width; d.sans("B", size) {
		size--
	}
	name := d.fit(t.Name, width-2)
	d.CellFormat(d.GetStringWidth(name)+2, 10, name, "", 0, "L", false, 0, "")
	if ticker != "" {
		d.sans("", 14)
		d.text(colMuted)
		d.CellFormat(0, 10, ticker, "", 0, "L", false, 0, "")
	}
	d.SetXY(textX, top+10)
	d.sans("", 10.5)
	d.text(colMuted)
	d.CellFormat(0, 6, typeWords(t.Type), "", 1, "L", false, 0, "")
	if end := top + logoSize + 3; d.GetY() < end && logoSize > 0 {
		d.SetY(end)
	} else {
		d.SetY(d.GetY() + 2)
	}
	// the details run the page's width, so they start below the tilted stamp
	d.SetY(max(d.GetY(), top+stampH+5))

	d.SetLeftMargin(pageMargin)
	d.keyValues(t.Details, 38)

	d.Ln(4)

	d.scopeBox(in.Scope)
	d.Ln(5)
	d.killTiles(in.Kills, in.Losses)

	d.Ln(4)
	d.findings(keyFindings(in))

	d.Ln(4)
	d.colophon(in)
}

// colophonWarnings close the Summary's note in the manner of a drug advert's side effects
const colophonWarnings = "Has been known to cause cancer in lab animals. " +
	"Side effects may include sudden urges to undock, compulsive staring at local, and waking at 03:00 EVE to form up for a timer. " +
	"Do not read while operating heavy machinery, or a titan. " +
	"Consult your FC if your killboard stays red for more than four hours. " +
	"Caveat lector."

// colophonAffiliates is how many affiliates the Summary's note names before "and N more"
const colophonAffiliates = 3

// colophon draws the Summary's closing note in italics, saying what search made the report and with which version
func (d *pageDoc) colophon(in Input) {
	const lineH = 4.8
	main := in.Target.Name
	if in.Target.Ticker != "" {
		main += " [" + in.Target.Ticker + "]"
	}
	affiliates := []string{}
	for _, source := range in.Scope.Sources {
		if !source.Main {
			affiliates = append(affiliates, source.Name)
		}
	}
	searched := main
	switch {
	case len(affiliates) > colophonAffiliates:
		searched += fmt.Sprintf(" and its affiliates %s, and %d more", strings.Join(affiliates[:colophonAffiliates], ", "), len(affiliates)-colophonAffiliates)
	case len(affiliates) > 1:
		searched += " and its affiliates " + strings.Join(affiliates[:len(affiliates)-1], ", ") + " and " + affiliates[len(affiliates)-1]
	case len(affiliates) == 1:
		searched += " and its affiliate " + affiliates[0]
	}

	before := "This report was generated by a search on " + searched + " using "
	version := "GoSleuth v" + in.AppVersion
	after := ". It is intended to give an at a glance intel report on the target's capabilities. " + colophonWarnings

	d.sans("I", 9)
	// the whole note stays on one page, with a line to spare as Write wraps a little differently
	d.keepTogether(float64(len(d.SplitText(before+version+after, bodyWidth))+1) * lineH)
	d.SetX(pageMargin)
	d.text(colMuted)
	d.Write(lineH, before)
	d.text(colAccent)
	if in.ReleasesURL != "" {
		d.WriteLinkString(lineH, version, in.ReleasesURL)
	} else {
		d.Write(lineH, version)
	}
	d.text(colMuted)
	d.Write(lineH, after)
	d.Ln(lineH)
	d.text(colText)
}

// stampW is the width of the Summary's stamp, at the top right beside the target's name
const stampW = 52.0

// stampH is the stamp's height before its tilt
const stampH = 17.0

// stamp draws a red "eyes only" stamp, tilted as if pressed on by hand, in a box of the width at x, y
func (d *pageDoc) stamp(x, y, w float64) {
	const h = stampH
	d.TransformBegin()
	d.TransformRotate(6, x+w/2, y+h/2)
	d.draw(colLoss)
	d.SetLineWidth(0.7)
	d.Rect(x, y, w, h, "D")
	d.SetLineWidth(0.25)
	d.Rect(x+1.2, y+1.2, w-2.4, h-2.4, "D")
	d.text(colLoss)
	d.SetXY(x, y+2.5)
	d.sans("B", 11)
	d.CellFormat(w, 6, "FOR YOUR EYES ONLY", "", 2, "C", false, 0, "")
	d.sans("B", 7)
	d.CellFormat(w, 4, "TOP SECRET · BURN BEFORE READING", "", 0, "C", false, 0, "")
	d.TransformEnd()
	// the colour and width are not part of the transform, so put back what the rest of the page expects
	d.draw(colRule)
	d.SetLineWidth(0.2)
	d.text(colText)
}

// typeWords turns the contract's type code into words
func typeWords(t string) string {
	switch strings.ToUpper(t) {
	case "CORPORATION":
		return "Corporation"
	case "ALLIANCE":
		return "Alliance"
	case "PILOT":
		return "Pilot"
	case "SYSTEM":
		return "System"
	}
	return t
}

// logo draws the target's logo, returning false (and drawing nothing) if it can't be read
func (d *pageDoc) logo(data []byte, x, y, size float64) bool {
	return d.image("logo", data, x, y, size, size)
}

// image draws a PNG or JPEG under a name unique to it in the document, returning false (and drawing nothing) if it can't be read. Drawing the same name again reuses it.
func (d *pageDoc) image(name string, data []byte, x, y, w, h float64) (ok bool) {
	kind := ""
	switch {
	case bytes.HasPrefix(data, []byte("\x89PNG\r\n\x1a\n")):
		kind = "PNG"
	case bytes.HasPrefix(data, []byte{0xFF, 0xD8, 0xFF}):
		kind = "JPG"
	default:
		return false
	}
	defer func() {
		if recover() != nil {
			ok = false
		}
	}()
	info := d.RegisterImageOptionsReader(name, fpdf.ImageOptions{ImageType: kind}, bytes.NewReader(data))
	if d.Error() != nil || info == nil {
		d.ClearError()
		return false
	}
	d.ImageOptions(name, x, y, w, h, false, fpdf.ImageOptions{ImageType: kind}, 0, "")
	if d.Error() != nil {
		d.ClearError()
		return false
	}
	return true
}

// scopeLine is one line of the scope box
type scopeText struct {
	text   string
	col    rgb
	style  string
	size   float64
	height float64
}

// scopeBox says what the search covered and any caveat on it, carried on to the next page in a box of its own when it doesn't fit, ie with many affiliates
func (d *pageDoc) scopeBox(s Scope) {
	line := func(text string, col rgb) scopeText { return scopeText{text, col, "", 9.5, 5.2} }
	lines := []scopeText{{"SCOPE", colAccent, "B", 9, 5}, {scopeLine(s), colText, "B", 9.5, 5.2}}
	for _, source := range s.Sources {
		lines = append(lines, line(sourceLine(source), colText))
	}
	for _, limit := range s.Limits {
		lines = append(lines, line(limit, colText))
	}
	if s.Stopped {
		lines = append(lines, line("The search was stopped early, so this covers only what was collected by then.", colWarn))
	}
	if s.RateLimited {
		lines = append(lines, line("The ESI rate limited the search, so killmails that needed it are missing.", colWarn))
	}
	lines = append(lines, scopeText{"Killmails show only deaths: not who survived, objectives, or fights that left no killmail.", colMuted, "", 8.5, 6})

	const pad = 2.5
	for len(lines) > 0 {
		// the lines that fit on this page, at least one on a fresh page so it always moves on
		n, height := 0, 0.0
		for n < len(lines) && height+lines[n].height <= d.room()-2*pad {
			height += lines[n].height
			n++
		}
		if n == 0 {
			if d.GetY() > pageMargin+1 {
				d.AddPage()
				continue
			}
			n, height = 1, lines[0].height
		}

		y := d.GetY()
		d.fill(colBoxBg)
		d.draw(colRule)
		d.SetLineWidth(0.2)
		d.RoundedRect(pageMargin, y, bodyWidth, height+2*pad, 1.5, "1234", "FD")
		d.SetY(y + pad)
		for _, l := range lines[:n] {
			d.SetX(pageMargin + 3)
			d.sans(l.style, l.size)
			d.text(l.col)
			d.CellFormat(bodyWidth-6, l.height, d.fit(l.text, bodyWidth-6), "", 1, "LM", false, 0, "")
		}
		d.SetY(y + height + 2*pad)
		if lines = lines[n:]; len(lines) > 0 {
			d.AddPage()
		}
	}
}

// scopeLine is "<N> killmails from <oldest> to <newest>"
func scopeLine(s Scope) string {
	if s.Killmails == 0 {
		return "No killmails"
	}
	return killmailSpan(s.Killmails, s.Oldest, s.Newest)
}

// sourceLine is one list's share, ie "   Ursa Major Holdings (main): 1,200 killmails from Aug 1st, 2026 to Oct 22nd, 2026"
func sourceLine(source Source) string {
	name := source.Name
	if source.Main {
		name += " (main)"
	}
	if source.Killmails == 0 {
		return "   " + name + ": no killmails"
	}
	return "   " + name + ": " + killmailSpan(source.Killmails, source.Oldest, source.Newest)
}

// killmailSpan is "<N> killmails from <oldest> to <newest>", or "on <date>" when both are the same day
func killmailSpan(n int, oldest, newest time.Time) string {
	word := " killmails"
	if n == 1 {
		word = " killmail"
	}
	text := count(n) + word
	if oldest.IsZero() || newest.IsZero() {
		return text
	}
	if spokenDate(oldest) == spokenDate(newest) {
		return text + " on " + spokenDate(newest)
	}
	return text + " from " + spokenDate(oldest) + " to " + spokenDate(newest)
}

// killTiles draws the kills and losses tiles side by side and the ISK efficiency under them
func (d *pageDoc) killTiles(kills, losses Tally) {
	// the heading, tiles, and efficiency line stay on one page
	d.keepTogether(52)
	d.heading("Kills and losses")
	d.Ln(1)
	gap := 6.0
	w := (bodyWidth - gap) / 2
	y := d.GetY()
	tile := func(x float64, label string, t Tally, fg, bg rgb) {
		d.fill(bg)
		d.draw(fg)
		d.SetLineWidth(0.3)
		d.RoundedRect(x, y, w, 30, 1.5, "1234", "FD")
		d.SetXY(x, y+3)
		d.sans("", 9)
		d.text(fg)
		d.CellFormat(w, 5, strings.ToUpper(label), "", 1, "C", false, 0, "")
		d.SetX(x)
		d.sans("B", 24)
		d.CellFormat(w, 12, count(t.Count), "", 1, "C", false, 0, "")
		d.SetX(x)
		d.sans("", 11)
		d.text(colText)
		d.CellFormat(w, 6, shortISK(t.ISK)+" ISK", "", 1, "C", false, 0, "")
	}
	tile(pageMargin, "Kills", kills, colKill, colKillBg)
	tile(pageMargin+w+gap, "Losses", losses, colLoss, colLossBg)
	d.SetXY(pageMargin, y+34)
	if total := kills.ISK + losses.ISK; total > 0 {
		d.sans("", 10)
		d.text(colText)
		d.CellFormat(bodyWidth, 6, "ISK efficiency: "+trimNum(kills.ISK/total*100, 0)+"%", "", 1, "L", false, 0, "")
	}
}
